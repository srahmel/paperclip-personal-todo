export function resolveLocale(value?: string | null): string {
  try {
    const locale = Intl.getCanonicalLocales(value || "en")[0];
    return /^(en|de)(-|$)/i.test(locale) ? locale : "en";
  } catch {
    return "en";
  }
}
const englishByGerman = new Map(
  Object.entries(german).map(([en, de]) => [de, en]),
);

export function createI18n(value?: string | null) {
  const locale = resolveLocale(value);
  const isGerman = locale.startsWith("de");
  const t = (key: string, values: Record<string, string | number> = {}) =>
    (isGerman ? (german[key] ?? key) : key).replace(
      /\{(\w+)\}/g,
      (placeholder, name: string) =>
        Object.hasOwn(values, name) ? String(values[name]) : placeholder,
    );
  return {
    locale,
    t,
    // Only known plugin messages are translated; arbitrary task/source content is preserved.
    message: (value: string) => t(englishByGerman.get(value) ?? value),
  };
}
